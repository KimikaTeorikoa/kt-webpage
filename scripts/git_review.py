#!/usr/bin/env python3
"""Optional validation and targeted commit helpers for content scripts."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path
from collections.abc import Sequence


ROOT = Path(__file__).resolve().parents[1]
COAUTHOR_TRAILER = "Co-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>"


def _relative_paths(paths: Sequence[Path]) -> list[str]:
    relative_paths: list[str] = []
    for path in paths:
        try:
            relative_paths.append(path.resolve().relative_to(ROOT).as_posix())
        except ValueError as error:
            raise ValueError(f"Cannot check or commit a path outside the repository: {path}") from error
    if not relative_paths:
        raise ValueError("No generated files were provided for Git checks.")
    return relative_paths


def _is_git_repository() -> bool:
    result = subprocess.run(
        ["git", "rev-parse", "--is-inside-work-tree"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.returncode == 0 and result.stdout.strip() == "true"


def ensure_generated_paths_clean(paths: Sequence[Path]) -> None:
    """Prevent content scripts from overwriting pre-existing changes to their targets."""
    relative_paths = _relative_paths(paths)
    if not _is_git_repository():
        return
    result = subprocess.run(
        ["git", "status", "--short", "--untracked-files=all", "--", *relative_paths],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode:
        raise RuntimeError(f"Could not inspect Git status:\n{result.stderr.strip()}")
    if result.stdout.strip():
        raise ValueError(
            "The file(s) this script needs to update already have Git changes. "
            "Commit or save those changes elsewhere first:\n"
            f"{result.stdout.rstrip()}"
        )


def _ask_yes_no(question: str) -> bool:
    while True:
        answer = input(f"{question} [yes/no]: ").strip().casefold()
        if answer in {"yes", "y"}:
            return True
        if answer in {"no", "n"}:
            return False
        print("Please answer yes or no.")


def review_and_commit(paths: Sequence[Path], commit_message: str) -> bool:
    """Run project checks and optionally commit only the files generated by the caller."""
    if not _ask_yes_no("Check Git status and validate the site"):
        print("Git checks skipped; no commit created.")
        return True

    relative_paths = _relative_paths(paths)
    if not _is_git_repository():
        print("There are problems: this directory is not a Git repository.", file=sys.stderr)
        return False

    try:
        status = subprocess.run(
            ["git", "status", "--short"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        print("Git status:")
        print(status.stdout.rstrip() or "(clean)")

        print("\nChecking patch whitespace...")
        subprocess.run(["git", "diff", "--check"], cwd=ROOT, check=True)
        subprocess.run(
            ["git", "diff", "--cached", "--check"],
            cwd=ROOT,
            check=True,
        )

        print("\nRunning project validation (make validate)...")
        subprocess.run(["make", "validate"], cwd=ROOT, check=True)
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"There are problems; no commit was created. {error}", file=sys.stderr)
        return False

    print("\nAll Git and site checks passed.")
    if not _ask_yes_no("Would you like to commit these changes"):
        print("Changes were not committed.")
        return True

    try:
        subprocess.run(["git", "add", "--", *relative_paths], cwd=ROOT, check=True)
        subprocess.run(
            [
                "git",
                "commit",
                "--only",
                "-m",
                commit_message,
                "-m",
                COAUTHOR_TRAILER,
                "--",
                *relative_paths,
            ],
            cwd=ROOT,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError) as error:
        print(
            "The checks passed, but the commit failed. Generated files may remain staged; "
            f"review `git status` before continuing. {error}",
            file=sys.stderr,
        )
        return False

    return True
